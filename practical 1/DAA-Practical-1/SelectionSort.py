def selection_sort(arr):
    n = len(arr)

    for i in range(n - 1):
        min_index = i

        for j in range(i + 1, n):
            if arr[j] < arr[min_index]:
                min_index = j

        arr[i], arr[min_index] = arr[min_index], arr[i]
arr = [29,7,8,5,6,1]
print("Before sorting:", arr)
selection_sort(arr)
print("After sorting:", arr)


